// `nyx init` — write a starter nyx.config.yaml into the CWD. The starter is
// the repo example's shape with two defaults changed so it works offline out
// of the box: the router chain points at the mock provider and the sandbox
// provider is local (development). An existing file is never overwritten
// without --force.

import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { loadConfig } from "@nyx/config";

export const STARTER_CONFIG_NAME = "nyx.config.yaml";

export const STARTER_CONFIG = `# SPDX-License-Identifier: AGPL-3.0-or-later
# Nyx starter configuration — generated by "nyx init".
# Works offline out of the box: the router points at the deterministic mock
# provider and the sandbox is the local (development) provider. Swap in real
# providers when ready; secrets never live in this file (see the comments).

# Headless by default: no "server" section. Add one (host/port/auth.owner_token)
# only when you also want the HTTP+SSE+WS surface.

providers:
  # Deterministic mock — no network, no key. Replace with a real provider:
  #   local llama.cpp / LM Studio / vLLM / Ollama (kind: openai, no api_key_env)
  #   hosted OpenAI-compatible endpoints (kind: openai, api_key_env: <ENV NAME>)
  #   Anthropic (kind: anthropic, api_key_env: <ENV NAME>)
  mock:
    kind: mock

router:
  default:
    chain:
      - provider: mock
        model: mock-1
    # fallback_on: [rate_limit, server_error, timeout]

  # Task-tagged rules override the default chain (match.task, e.g. compaction).
  rules: []

  budgets:
    per_turn_tokens: 200000
    per_session_tokens: 5000000
    on_exceed: ask

# Deny > ask > allow. The recommended default ruleset: read-only tools run
# free, everything else asks. Structural invariants (R4 always asks) are
# enforced by the engine and cannot be weakened here.
policy:
  rules:
    - id: allow-r0
      match: { risk: R0 }
      decision: allow
      reason: "Read-only tools (fs.read, listings) run without interruption."
    - id: allow-r1
      match: { risk: R1 }
      decision: allow
      reason: "Low-risk local actions are auto-allowed and audit-logged."
    - id: ask-r2
      match: { risk: R2 }
      decision: ask
      reason: "Mutating local actions require a one-shot approval."
    - id: ask-r3
      match: { risk: R3 }
      decision: ask
      reason: "Higher-impact actions require explicit approval."
    - id: ask-r4
      match: { risk: R4 }
      decision: ask
      reason: "Owner-level actions always route to the owner approval channel."

# Local sandbox: development only (no network isolation); it refuses to run
# when NYX_ENV=production. Switch to docker (image alpine:3.20) for isolation.
sandbox:
  provider: local
  workdir_root: ~/.nyx/sandboxes

memory:
  root: ~/.nyx/memory
  episode_expiry_days: 30

persona:
  default_id: default
  root: ./personas

logging:
  level: info
  redact: [api_key, authorization, token, secret]

owner_id: owner
`;

export interface InitResult {
  path: string;
  written: boolean;
  /** True when a file already existed and --force was required. */
  refused: boolean;
}

/** Write the starter config into `dir` (default CWD); never clobber without force. */
export async function runInit(dir: string, opts: { force?: boolean } = {}): Promise<InitResult> {
  const path = join(dir, STARTER_CONFIG_NAME);
  if (existsSync(path) && opts.force !== true) {
    return { path, written: false, refused: true };
  }
  await writeFile(path, STARTER_CONFIG, "utf8");
  // The starter must always be loadable — a broken template is a bug we want
  // to hear about loudly, so verify before reporting success.
  await loadConfig(path);
  return { path, written: true, refused: false };
}

/** The "next steps" block printed after a successful init. */
export function initNextSteps(result: InitResult): string {
  return [
    `wrote ${result.path}`,
    "",
    "next steps:",
    "  nyx doctor                 verify your setup (node, sqlite, providers, sandbox)",
    '  nyx run "hello"            one-shot turn against the mock provider (offline)',
    "  nyx chat                   interactive TUI (streaming, tools, approvals)",
    "",
    "to use a real model, edit providers + router in nyx.config.yaml:",
    "  providers:                 # e.g. llama.cpp / LM Studio / vLLM / Ollama",
    '    local: { kind: openai, base_url: "http://127.0.0.1:8080/v1", models: [...] }',
    "  router.default.chain:      # - { provider: local, model: <your model id> }",
    "",
    "non-interactive runs deny pending approvals after 2s — use `nyx chat` to approve live.",
  ].join("\n");
}
